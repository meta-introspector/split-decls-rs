use module_wrapper_macros::{conditional_wrapper, test_wrapper};

// Example: Conditionally use wrapped nom
#[cfg(feature = "test-nom")]
conditional_wrapper!(
    feature = "use_wrapped_nom",
    original = nom,
    wrapper = crate::wrapped::nom_wrapper
);

// Example: Conditionally use wrapped hashbrown
#[cfg(feature = "test-hashbrown")]
conditional_wrapper!(
    feature = "use_wrapped_hashbrown", 
    original = hashbrown,
    wrapper = crate::wrapped::hashbrown_wrapper
);

// Module for wrapped implementations
#[cfg(any(feature = "test-nom", feature = "test-hashbrown"))]
mod wrapped {
    #[cfg(feature = "test-nom")]
    pub mod nom_wrapper {
        // This would be generated by split-decls-rs
        // For now, just re-export original
        pub use nom::*;
    }
    
    #[cfg(feature = "test-hashbrown")]
    pub mod hashbrown_wrapper {
        // This would be generated by split-decls-rs
        // For now, just re-export original
        pub use hashbrown::*;
    }
}

// Generate tests for each wrapper
#[cfg(feature = "test-nom")]
test_wrapper!(crate::wrapped::nom_wrapper, nom_wrapper_tests);

#[cfg(feature = "test-hashbrown")]
test_wrapper!(crate::wrapped::hashbrown_wrapper, hashbrown_wrapper_tests);

#[cfg(test)]
mod integration_tests {
    use super::*;
    
    #[test]
    fn test_harness_compiles() {
        assert!(true);
    }
    
    #[cfg(feature = "test-nom")]
    #[test]
    fn test_nom_wrapper_basic() {
        // Basic test that nom wrapper works
        use nom::bytes::complete::tag;
        let result = tag::<_, _, nom::error::Error<_>>("hello")("hello world");
        assert!(result.is_ok());
    }
    
    #[cfg(feature = "test-hashbrown")]
    #[test]
    fn test_hashbrown_wrapper_basic() {
        // Basic test that hashbrown wrapper works
        use hashbrown::HashMap;
        let mut map = HashMap::new();
        map.insert("key", "value");
        assert_eq!(map.get("key"), Some(&"value"));
    }
}
