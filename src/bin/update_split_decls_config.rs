fn generate_preservation_proof(config: &SplitDeclsConfig, cargo2nix_root: &Path) -> Result<String> {
    let mut proof = String::new();
    proof.push_str("# Crate Preservation Proof\n\n");
    proof.push_str(&format!("Generated: {}\n", chrono::Utc::now().format("%Y-%m-%d %H:%M:%S UTC")));
    proof.push_str(&format!("Total crates: {}\n\n", config.wrapping.crates.len()));
    
    proof.push_str("## Preservation Verification\n\n");
    
    let mut preserved_count = 0;
    let mut missing_count = 0;
    
    for crate_name in &config.wrapping.crates {
        if let Some(path_str) = config.crate_path_overrides.get(crate_name) {
            let path = Path::new(path_str);
            let exists = path.exists();
            let cargo_toml_exists = path.join("Cargo.toml").exists();
            
            if exists && cargo_toml_exists {
                preserved_count += 1;
                proof.push_str(&format!("✅ `{}` → `{}`\n", crate_name, path_str));
            } else {
                missing_count += 1;
                proof.push_str(&format!("❌ `{}` → `{}` (missing)\n", crate_name, path_str));
            }
        } else {
            missing_count += 1;
            proof.push_str(&format!("❌ `{}` → (no path mapping)\n", crate_name));
        }
    }
    
    proof.push_str(&format!("\n## Summary\n\n"));
    proof.push_str(&format!("- **Preserved**: {}\n", preserved_count));
    proof.push_str(&format!("- **Missing**: {}\n", missing_count));
    proof.push_str(&format!("- **Preservation Rate**: {:.1}%\n", 
        (preserved_count as f64 / config.wrapping.crates.len() as f64) * 100.0));
    
    if missing_count == 0 {
        proof.push_str("\n🎉 **ALL CRATES PRESERVED** - Ready for bootstrap!\n");
    } else {
        proof.push_str(&format!("\n⚠️  {} crates need attention before bootstrap\n", missing_count));
    }
    
    Ok(proof)
}


// --- Structs for SplitDeclsConfig (from split-decls-types/src/lib.rs) ---
// Duplicated here to avoid circular dependency for this tool.
// In a real project, this would be a shared library.
#[derive(Debug, Default, Serialize, Deserialize)]
struct SplitDeclsConfig {
    #[serde(default)]
    wrapping: WrappingConfig,
    #[serde(default)]
    crate_path_overrides: HashMap<String, String>, // Changed from PathBuf for simpler TOML serialization
    pub explicit_crate_path_mappings: Option<HashMap<String, String>>, // Corrected to Option
    #[serde(default)]
    pub workspace_dependency_overrides: Option<HashMap<String, Value>>,
}

#[derive(Debug, Default, Serialize, Deserialize)]
struct WrappingConfig {
    #[serde(default)]
    crates: Vec<String>,
}

#[derive(Debug, Default, Serialize, Deserialize)]
struct CratePathsOnly {
    #[serde(default)]
    crate_path_overrides: HashMap<String, String>,
}


fn main() -> Result<()> {
    let args = Args::parse();

    // 1. Load existing split-decls-rs.toml
    let mut split_decls_config_content = fs::read_to_string(&args.split_decls_config_path).unwrap_or_default();
    let mut split_decls_data: SplitDeclsConfig = toml::from_str(&split_decls_config_content).unwrap_or_default();

    let mut existing_crates_to_wrap: HashSet<String> = split_decls_data.wrapping.crates.iter().cloned().collect();
    let mut existing_path_overrides: HashMap<String, String> = split_decls_data.crate_path_overrides.iter().map(|(k, v)| (k.clone(), v.clone())).collect();

    let split_decls_rs_root = env::current_dir()?;
    let cargo2nix_root = split_decls_rs_root.parent().context("Failed to get parent of split-decls-rs")?.parent().context("Failed to get cargo2nix root")?;

    // Use cargo-lock import to get dependency information
    let cargo_lock_data = import_cargo_lock!("../../../Cargo.lock");
    for crate_info in cargo_lock_data {
        existing_crates_to_wrap.insert(crate_info.name.to_string());

        let crate_path = Path::new(crate_info.path);
        let absolute_crate_path = if crate_path.is_absolute() {
            crate_path.to_path_buf()
        } else {
            // Resolve all paths relative to the cargo2nix root
            let candidate_path = cargo2nix_root.join(crate_path);
            match candidate_path.canonicalize() {
                Ok(path) => path,
                Err(_) => {
                    // If canonicalize fails, just use the joined path
                    // This handles cases where the path doesn't exist yet
                    candidate_path
                }
            }
        };
        // println!("DEBUG: Crate: {}, Original Path: {}, Absolute Path: {}", crate_info.name, crate_info.path, absolute_crate_path.display());
        existing_path_overrides.insert(crate_info.name.to_string(), absolute_crate_path.to_string_lossy().into_owned());
    }

    // Special handling for the current project itself
    existing_crates_to_wrap.insert("split-decls-rs".to_string());
    existing_path_overrides.insert("split-decls-rs".to_string(), split_decls_rs_root.to_string_lossy().into_owned());
    
    // Filter out internal crates of split-decls-rs itself (if any from cargo tree)
    // and other crates that are part of the larger original workspace where RootCargo.toml is located
    // but are not intended to be wrapped by split-decls-rs
    let internal_crates_to_skip: HashSet<&str> = [
        "split-decls-types",
        "cargo-toml-generator-types",
        "cargo-toml-generator-macros",
        "cargo-toml-parts",
        "pagerank_rs",
        // Add other crate names here that should not be wrapped as individual units
        // or whose paths are handled explicitly.
    ].iter().cloned().collect();

    // existing_crates_to_wrap.retain(|crate_name| {
    //     !internal_crates_to_skip.contains(crate_name.as_str()) && !crate_name.starts_with("split-decls-rs-")
    // });


    // Sort crates for consistent output
    let mut sorted_crates: Vec<String> = existing_crates_to_wrap.into_iter().collect();
    sorted_crates.sort();
    split_decls_data.wrapping.crates = sorted_crates;
    
    // Apply explicit_crate_path_mappings from config, giving them precedence over derived paths
    if let Some(explicit_mappings) = split_decls_data.explicit_crate_path_mappings.take() { // Use .take() to move out of the Option
        for (crate_name, path_str) in explicit_mappings {
            existing_path_overrides.insert(crate_name, path_str);
        }
    }

    // Sort overrides by key for consistent output
    let mut sorted_overrides: Vec<(String, String)> = existing_path_overrides.into_iter().collect();
    sorted_overrides.sort_by(|a, b| a.0.cmp(&b.0));
    
    // Validate and fix paths
    let mut validated_overrides = HashMap::new();
    for (crate_name, path_str) in sorted_overrides {
        let path = Path::new(&path_str);
        if path.join("Cargo.toml").exists() {
            validated_overrides.insert(crate_name, path_str);
        } else {
            // Try to find the correct path
            let possible_paths = [
                format!("/home/mdupont/nix/vendor/rust/cargo2nix/crates/{}", crate_name),
                format!("/home/mdupont/nix/vendor/rust/cargo2nix/submodules/{}", crate_name),
                format!("/home/mdupont/nix/vendor/rust/cargo2nix/submodules/rust/compiler/{}", crate_name),
                format!("/home/mdupont/nix/vendor/rust/cargo2nix/submodules/rust/library/{}", crate_name),
                format!("/home/mdupont/nix/vendor/rust/cargo2nix/tools/{}", crate_name),
            ];
            
            let mut found = false;
            for possible_path in &possible_paths {
                if Path::new(possible_path).join("Cargo.toml").exists() {
                    println!("Fixed path for {}: {} -> {}", crate_name, path_str, possible_path);
                    validated_overrides.insert(crate_name.clone(), possible_path.clone());
                    found = true;
                    break;
                }
            }
            
            if !found {
                println!("Warning: Could not find valid path for {}: {}", crate_name, path_str);
                validated_overrides.insert(crate_name, path_str); // Keep original for now
            }
        }
    }
    
    split_decls_data.crate_path_overrides = validated_overrides;


    // Generate preservation proof
    let preservation_proof = generate_preservation_proof(&split_decls_data, &cargo2nix_root)?;
    
    // Write updated split-decls-rs.toml
    let updated_toml_content = toml::to_string_pretty(&split_decls_data)
        .context("Failed to serialize updated split-decls-rs.toml")?;
    fs::write(&args.split_decls_config_path, updated_toml_content)
        .context(format!("Failed to write to {}", args.split_decls_config_path.display()))?;

    // Write preservation proof
    fs::write("crate_preservation_proof.md", preservation_proof)
        .context("Failed to write preservation proof")?;

    println!("Successfully updated {}", args.split_decls_config_path.display());
    println!("Generated crate preservation proof: crate_preservation_proof.md");

    Ok(())
}

