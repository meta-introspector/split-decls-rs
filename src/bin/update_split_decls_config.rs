//! This tool (`update_split_decls_config`) is responsible for automatically updating the `split-decls-rs.toml`
//! configuration file. This file dictates which crates are processed by `split-decls-rs`
//! and how their paths are resolved.
//!
//! # Configuration File Structure (`split-decls-rs.toml`)
//!
//! The `split-decls-rs.toml` file is a TOML-formatted configuration with the following key sections:
//!
//! -   **`[wrapping]`**: This section contains a list of `crates` that `split-decls-rs`
//!     should process and "wrap" into a new workspace.
//!     ```toml
//!     [wrapping]
//!     crates = [
//!         "my-crate-a",
//!         "my-crate-b",
//!         # ...
//!     ]
//!     ```
//!     This list is automatically populated by `update_split_decls_config` based on the
//!     `cargo tree` output of the project, identifying all local path dependencies.
//!
//! -   **`[crate_path_overrides]`**: This section maps crate names to their absolute file system paths.
//!     `split-decls-rs` uses these paths to locate the source code of each crate.
//!     ```toml
//!     [crate_path_overrides]
//!     "my-crate-a" = "/absolute/path/to/my-crate-a"
//!     "my-crate-b" = "/absolute/path/to/my-crate-b"
//!     # ...
//!     ```
//!     These paths are also automatically generated by `update_split_decls_config`.
//!
//! -   **`explicit_crate_path_mappings`**: (Optional) This field within the main configuration allows
//!     users to explicitly define or override crate paths. Mappings provided here take
//!     precedence over any paths automatically derived from `cargo tree`. This is particularly
//!     useful for:
//!     -   **Overriding automatically detected paths**: If the automatic detection provides an
//!         incorrect or undesirable path for a crate.
//!     -   **Including crates not detected by `cargo tree`**: For example, if a crate is
//!         dynamically loaded or not part of the standard dependency graph, but you still
//!         want `split-decls-rs` to process it.
//!     -   **Specifying alternative versions/forks**: To point `split-decls-rs` to a local
//!         fork or a specific version of a crate not typically resolved by `cargo tree`.
//!     ```toml
//!     explicit_crate_path_mappings = {
//!         "some-crate" = "/custom/path/to/some-crate",
//!         "another-crate" = "/local/fork/of/another-crate"
//!     }
//!     ```
//!
//! # How to Add New Crates
//!
//! To add a new crate to be processed by `split-decls-rs`:
//!
//! 1.  **Add the crate as a dependency**: Ensure the new crate is a local path dependency within
//!     your project's `Cargo.toml` (or `RootCargo.toml` if using a workspace).
//! 2.  **Run `update_split_decls_config`**: Execute this tool against your `split-decls-rs.toml` file.
//!     The tool will automatically detect the new crate via `cargo tree`, add it to the `[wrapping].crates`
//!     list, and generate its corresponding path in `[crate_path_overrides]`.
//!     ```bash
//!     cargo run --bin update_split_decls_config -- --split-decls-config-path split-decls-rs.toml
//!     ```
//! 3.  **Manual Overrides (Optional)**: If you need to specify a custom path or include a crate
//!     not automatically detected, add an entry to `explicit_crate_path_mappings` in your
//!     `split-decls-rs.toml` file. These explicit mappings will always take precedence.
//!
use clap::Parser;
use anyhow::{Context, Result};
use std::collections::{HashSet, HashMap};
use std::fs;
use std::env;
use std::path::{Path, PathBuf};
use toml::{self, Table, Value};
use serde::{Deserialize, Serialize};
use cargo_metadata_lib::get_cargo_tree_data;
use cargo_metadata_lib::CrateInfo;


// --- Structs for SplitDeclsConfig (from split-decls-types/src/lib.rs) ---
// Duplicated here to avoid circular dependency for this tool.
// In a real project, this would be a shared library.
#[derive(Debug, Default, Serialize, Deserialize)]
struct SplitDeclsConfig {
    #[serde(default)]
    wrapping: WrappingConfig,
    #[serde(default)]
    crate_path_overrides: HashMap<String, String>, // Changed from PathBuf for simpler TOML serialization
    pub explicit_crate_path_mappings: Option<HashMap<String, String>>, // Corrected to Option
}

#[derive(Debug, Default, Serialize, Deserialize)]
struct WrappingConfig {
    #[serde(default)]
    crates: Vec<String>,
}

#[derive(Debug, Default, Serialize, Deserialize)]
struct CratePathsOnly {
    #[serde(default)]
    crate_path_overrides: HashMap<String, String>,
}


fn main() -> Result<()> {
    let args = Args::parse();

    // 1. Load existing split-decls-rs.toml
    let mut split_decls_config_content = fs::read_to_string(&args.split_decls_config_path).unwrap_or_default();
    let mut split_decls_data: SplitDeclsConfig = toml::from_str(&split_decls_config_content).unwrap_or_default();

    let mut existing_crates_to_wrap: HashSet<String> = split_decls_data.wrapping.crates.iter().cloned().collect();
    let mut existing_path_overrides: HashMap<String, String> = split_decls_data.crate_path_overrides.iter().map(|(k, v)| (k.clone(), v.clone())).collect();

    let split_decls_rs_root = env::current_dir()?;
    let cargo2nix_root = split_decls_rs_root.parent().context("Failed to get parent of split-decls-rs")?.parent().context("Failed to get cargo2nix root")?;

    // Use cargo-tree-macro to get dependency information
    for crate_info in get_cargo_tree_data() {
        existing_crates_to_wrap.insert(crate_info.name.to_string());

        let crate_path = Path::new(crate_info.path);
        let absolute_crate_path = if crate_path.is_absolute() {
            crate_path.to_path_buf()
        } else {
            // Resolve all paths relative to the cargo2nix root
            cargo2nix_root.join(crate_path).canonicalize()?
        };
        // println!("DEBUG: Crate: {}, Original Path: {}, Absolute Path: {}", crate_info.name, crate_info.path, absolute_crate_path.display());
        existing_path_overrides.insert(crate_info.name.to_string(), absolute_crate_path.to_string_lossy().into_owned());
    }

    // Special handling for the current project itself
    existing_crates_to_wrap.insert("split-decls-rs".to_string());
    existing_path_overrides.insert("split-decls-rs".to_string(), split_decls_rs_root.to_string_lossy().into_owned());
    
    // Filter out internal crates of split-decls-rs itself (if any from cargo tree)
    // and other crates that are part of the larger original workspace where RootCargo.toml is located
    // but are not intended to be wrapped by split-decls-rs
    let internal_crates_to_skip: HashSet<&str> = [
        "split-decls-types",
        "cargo-toml-generator-types",
        "cargo-toml-generator-macros",
        "cargo-toml-parts",
        "pagerank_rs",
        // Add other crate names here that should not be wrapped as individual units
        // or whose paths are handled explicitly.
    ].iter().cloned().collect();

    // existing_crates_to_wrap.retain(|crate_name| {
    //     !internal_crates_to_skip.contains(crate_name.as_str()) && !crate_name.starts_with("split-decls-rs-")
    // });


    // Sort crates for consistent output
    let mut sorted_crates: Vec<String> = existing_crates_to_wrap.into_iter().collect();
    sorted_crates.sort();
    split_decls_data.wrapping.crates = sorted_crates;
    
    // Apply explicit_crate_path_mappings from config, giving them precedence over derived paths
    if let Some(explicit_mappings) = split_decls_data.explicit_crate_path_mappings.take() { // Use .take() to move out of the Option
        for (crate_name, path_str) in explicit_mappings {
            existing_path_overrides.insert(crate_name, path_str);
        }
    }

    // Sort overrides by key for consistent output
    let mut sorted_overrides: Vec<(String, String)> = existing_path_overrides.into_iter().collect();
    sorted_overrides.sort_by(|a, b| a.0.cmp(&b.0));
    split_decls_data.crate_path_overrides = sorted_overrides.into_iter().collect();


    // Write updated split-decls-rs.toml
    let updated_toml_content = toml::to_string_pretty(&split_decls_data)
        .context("Failed to serialize updated split-decls-rs.toml")?;
    fs::write(&args.split_decls_config_path, updated_toml_content)
        .context(format!("Failed to write to {}", args.split_decls_config_path.display()))?;

    println!("Successfully updated {}", args.split_decls_config_path.display());

    Ok(())
}

#[derive(Parser, Debug)]
#[clap(author, version, about, long_about = None)]
struct Args {
    /// Path to the split-decls-rs.toml configuration file to update
    #[clap(long)]
    split_decls_config_path: PathBuf,
}

