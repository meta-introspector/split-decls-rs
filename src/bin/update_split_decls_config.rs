//! This tool (`update_split_decls_config`) is responsible for automatically updating the `split-decls-rs.toml`
//! configuration file. This file dictates which crates are processed by `split-decls-rs`
//! and how their paths are resolved.
//!
//! # Configuration File Structure (`split-decls-rs.toml`)
//!
//! The `split-decls-rs.toml` file is a TOML-formatted configuration with the following key sections:
//!
//! -   **`[wrapping]`**: This section contains a list of `crates` that `split-decls-rs`
//!     should process and "wrap" into a new workspace.
//!     ```toml
//!     [wrapping]
//!     crates = [
//!         "my-crate-a",
//!         "my-crate-b",
//!         # ...
//!     ]
//!     ```
//!     This list is automatically populated by `update_split_decls_config` based on the
//!     `cargo tree` output of the project, identifying all local path dependencies.
//!
//! -   **`[crate_path_overrides]`**: This section maps crate names to their absolute file system paths.
//!     `split-decls-rs` uses these paths to locate the source code of each crate.
//!     ```toml
//!     [crate_path_overrides]
//!     "my-crate-a" = "/absolute/path/to/my-crate-a"
//!     "my-crate-b" = "/absolute/path/to/my-crate-b"
//!     # ...
//!     ```
//!     These paths are also automatically generated by `update_split_decls_config`.
//!
//! -   **`explicit_crate_path_mappings`**: (Optional) This field within the main configuration allows
//!     users to explicitly define or override crate paths. Mappings provided here take
//!     precedence over any paths automatically derived from `cargo tree`. This is particularly
//!     useful for:
//!     -   **Overriding automatically detected paths**: If the automatic detection provides an
//!         incorrect or undesirable path for a crate.
//!     -   **Including crates not detected by `cargo tree`**: For example, if a crate is
//!         dynamically loaded or not part of the standard dependency graph, but you still
//!         want `split-decls-rs` to process it.
//!     -   **Specifying alternative versions/forks**: To point `split-decls-rs` to a local
//!         fork or a specific version of a crate not typically resolved by `cargo tree`.
//!     ```toml
//!     explicit_crate_path_mappings = {
//!         "some-crate" = "/custom/path/to/some-crate",
//!         "another-crate" = "/local/fork/of/another-crate"
//!     }
//!     ```
//!
//! # How to Add New Crates
//!
//! To add a new crate to be processed by `split-decls-rs`:
//!
//! 1.  **Add the crate as a dependency**: Ensure the new crate is a local path dependency within
//!     your project's `Cargo.toml` (or `RootCargo.toml` if using a workspace).
//! 2.  **Run `update_split_decls_config`**: Execute this tool against your `split-decls-rs.toml` file.
//!     The tool will automatically detect the new crate via `cargo tree`, add it to the `[wrapping].crates`
//!     list, and generate its corresponding path in `[crate_path_overrides]`.
//!     ```bash
//!     cargo run --bin update_split_decls_config -- --split-decls-config-path split-decls-rs.toml
//!     ```
//! 3.  **Manual Overrides (Optional)**: If you need to specify a custom path or include a crate
//!     not automatically detected, add an entry to `explicit_crate_path_mappings` in your
//!     `split-decls-rs.toml` file. These explicit mappings will always take precedence.
//!
