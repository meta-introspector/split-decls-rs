use std::path::Path;
use anyhow::Result;
use clap::{Parser, Subcommand};
use split_decls_rs::syscall_oracle::{
    SyscallInterceptor, SyscallAstTransformer, create_default_syscall_interceptor, 
    generate_oracle_types, TypeSafetyLevel
};

#[derive(Parser)]
#[command(name = "syscall-oracle")]
#[command(about = "Syscall Oracle - Type-safe syscall interception with DAO governance")]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    /// Generate oracle types and macros
    Generate {
        /// Output file for oracle types
        #[arg(short, long, default_value = "src/syscall_oracles.rs")]
        output: String,
    },
    
    /// Transform directory with syscall interception
    Transform {
        /// Directory to transform
        #[arg(short, long)]
        dir: String,
        
        /// Output directory for transformed files
        #[arg(short, long, default_value = "syscall_wrapped")]
        output: String,
        
        /// Enable mock mode
        #[arg(short, long)]
        mock: bool,
        
        /// Type safety level
        #[arg(short, long, default_value = "strict")]
        safety: String,
        
        /// Enable DAO governance
        #[arg(long)]
        dao: bool,
    },
    
    /// Generate default syscall interceptor config
    Config {
        /// Output config file
        #[arg(short, long, default_value = "syscall_config.json")]
        output: String,
    },
    
    /// Interactive syscall wrapping
    Interactive {
        /// Target directory
        #[arg(short, long, default_value = "output2")]
        dir: String,
    },
    
    /// Analyze syscalls in directory
    Analyze {
        /// Directory to analyze
        #[arg(short, long)]
        dir: String,
        
        /// Generate interceptor config from analysis
        #[arg(short, long)]
        generate: bool,
    },
}

fn main() -> Result<()> {
    let cli = Cli::parse();
    
    match cli.command {
        Commands::Generate { output } => {
            generate_oracle_code(&output)
        }
        
        Commands::Transform { dir, output, mock, safety, dao } => {
            transform_directory(&dir, &output, mock, &safety, dao)
        }
        
        Commands::Config { output } => {
            generate_config(&output)
        }
        
        Commands::Interactive { dir } => {
            run_interactive_mode(&dir)
        }
        
        Commands::Analyze { dir, generate } => {
            analyze_syscalls(&dir, generate)
        }
    }
}

fn generate_oracle_code(output: &str) -> Result<()> {
    println!("🔮 Generating syscall oracle types and macros...");
    
    let oracle_code = generate_oracle_types();
    let formatted_code = format!(
        "// Auto-generated syscall oracle types and macros\n// Generated by syscall-oracle tool\n\n{}", 
        oracle_code.to_string()
    );
    
    std::fs::write(output, formatted_code)?;
    
    println!("✅ Generated oracle types: {}", output);
    println!("📋 Includes:");
    println!("   • SystemOracle trait");
    println!("   • FileSystemOracle, ProcessOracle, NetworkOracle");
    println!("   • Type-safe wrapper macros");
    println!("   • DAO governance types");
    
    Ok(())
}

fn transform_directory(dir: &str, output: &str, mock: bool, safety: &str, dao: bool) -> Result<()> {
    println!("🛡️ Transforming directory with syscall interception...");
    println!("   Source: {}", dir);
    println!("   Output: {}", output);
    println!("   Mock mode: {}", mock);
    println!("   Safety level: {}", safety);
    println!("   DAO governance: {}", dao);
    
    let safety_level = match safety {
        "permissive" => TypeSafetyLevel::Permissive,
        "strict" => TypeSafetyLevel::Strict,
        "paranoid" => TypeSafetyLevel::Paranoid,
        _ => TypeSafetyLevel::Strict,
    };
    
    let mut interceptor = create_default_syscall_interceptor();
    interceptor.mock_mode = mock;
    interceptor.dao_governance = dao;
    interceptor.type_safety_level = safety_level;
    
    let mut transformer = SyscallAstTransformer::new(interceptor);
    
    // Create output directory
    std::fs::create_dir_all(output)?;
    
    let mut transformed_count = 0;
    
    for entry in walkdir::WalkDir::new(dir) {
        let entry = entry?;
        if entry.file_type().is_file() && 
           entry.path().extension().map_or(false, |ext| ext == "rs") {
            
            match transformer.transform_file(entry.path()) {
                Ok(transformed_code) => {
                    let relative_path = entry.path().strip_prefix(dir)?;
                    let output_path = Path::new(output).join(relative_path);
                    
                    if let Some(parent) = output_path.parent() {
                        std::fs::create_dir_all(parent)?;
                    }
                    
                    std::fs::write(&output_path, transformed_code)?;
                    transformed_count += 1;
                    
                    if transformed_count % 100 == 0 {
                        println!("   Transformed {} files...", transformed_count);
                    }
                }
                Err(e) => {
                    eprintln!("⚠️ Failed to transform {:?}: {}", entry.path(), e);
                }
            }
        }
    }
    
    println!("✅ Transformation completed!");
    println!("   Files transformed: {}", transformed_count);
    
    Ok(())
}

fn generate_config(output: &str) -> Result<()> {
    let interceptor = create_default_syscall_interceptor();
    let json = serde_json::to_string_pretty(&interceptor)?;
    std::fs::write(output, json)?;
    
    println!("📋 Generated syscall interceptor config: {}", output);
    println!("🔧 Edit this file to customize syscall interception");
    
    println!("\n🛡️ Default syscall mappings:");
    for (call, wrapper) in &interceptor.syscall_mappings {
        println!("   • {} -> {} ({})", call, wrapper.wrapper_macro, wrapper.safety_wrapper);
    }
    
    Ok(())
}

fn run_interactive_mode(target_dir: &str) -> Result<()> {
    println!("🎯 Interactive Syscall Oracle Mode");
    println!("==================================");
    
    loop {
        println!("\n🛡️ Available commands:");
        println!("  1. Transform with mock mode");
        println!("  2. Transform with strict type safety");
        println!("  3. Transform with DAO governance");
        println!("  4. Analyze syscalls in directory");
        println!("  5. Generate oracle types");
        println!("  6. Exit");
        
        print!("\nEnter choice (1-6): ");
        std::io::Write::flush(&mut std::io::stdout())?;
        
        let mut input = String::new();
        std::io::stdin().read_line(&mut input)?;
        
        match input.trim() {
            "1" => {
                transform_directory(target_dir, "mock_wrapped", true, "strict", false)?;
            }
            
            "2" => {
                transform_directory(target_dir, "type_safe_wrapped", false, "strict", false)?;
            }
            
            "3" => {
                transform_directory(target_dir, "dao_governed_wrapped", false, "paranoid", true)?;
            }
            
            "4" => {
                analyze_syscalls(target_dir, true)?;
            }
            
            "5" => {
                generate_oracle_code("interactive_oracles.rs")?;
            }
            
            "6" => {
                println!("👋 Goodbye!");
                break;
            }
            
            _ => {
                println!("❌ Invalid choice, please enter 1-6");
            }
        }
    }
    
    Ok(())
}

fn analyze_syscalls(dir: &str, generate_config: bool) -> Result<()> {
    println!("🔍 Analyzing syscalls in directory: {}", dir);
    
    let mut syscall_counts: std::collections::HashMap<String, usize> = std::collections::HashMap::new();
    let mut file_count = 0;
    
    for entry in walkdir::WalkDir::new(dir) {
        let entry = entry?;
        if entry.file_type().is_file() && 
           entry.path().extension().map_or(false, |ext| ext == "rs") {
            
            if let Ok(content) = std::fs::read_to_string(entry.path()) {
                file_count += 1;
                
                // Simple pattern matching for syscalls
                let syscall_patterns = [
                    "std::fs::", "std::process::", "std::net::", "libc::",
                    "std::time::", "std::env::", "std::io::",
                ];
                
                for pattern in &syscall_patterns {
                    let count = content.matches(pattern).count();
                    if count > 0 {
                        *syscall_counts.entry(pattern.to_string()).or_insert(0) += count;
                    }
                }
            }
        }
    }
    
    println!("📊 Syscall Analysis Results:");
    println!("   Files analyzed: {}", file_count);
    println!("   Syscall patterns found:");
    
    let mut sorted_syscalls: Vec<_> = syscall_counts.iter().collect();
    sorted_syscalls.sort_by(|a, b| b.1.cmp(a.1));
    
    for (pattern, count) in &sorted_syscalls {
        println!("     • {}: {} occurrences", pattern, count);
    }
    
    if generate_config && !syscall_counts.is_empty() {
        println!("\n🔧 Generating targeted interceptor config...");
        
        let mut interceptor = create_default_syscall_interceptor();
        
        // Add high-frequency syscalls to interceptor
        for (pattern, count) in &sorted_syscalls {
            if *count > 10 {
                println!("   Adding high-frequency pattern: {} ({} uses)", pattern, count);
            }
        }
        
        let json = serde_json::to_string_pretty(&interceptor)?;
        std::fs::write("analyzed_syscall_config.json", json)?;
        
        println!("💾 Generated config: analyzed_syscall_config.json");
    }
    
    Ok(())
}
