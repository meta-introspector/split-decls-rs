fn generate_specific_trait(category: &str, output: &str) -> Result<()> {
    println!("🔧 Generating {} trait...", category);
    
    let generator = SyscallDecouplingGenerator::new();
    let template = generator.generate_decoupling_template();
    
    let matching_trait = template.syscall_traits.iter()
        .find(|t| t.name.to_lowercase().contains(&category.to_lowercase()));
    
    if let Some(trait_def) = matching_trait {
        let rust_code = generator.generate_trait_code(trait_def);
        
        let formatted_code = format!(
            "// Generated {} trait for syscall decoupling\n\n{}", 
            trait_def.name,
            rust_code.to_string()
        );
        
        
    std::fs::write(output, formatted_code)?;
        
        println!("✅ Generated {} trait: {}", trait_def.name, output);
        println!("   Methods: {}", trait_def.methods.len());
        println!("   Safety: {:?}", trait_def.safety_level);
    } else {
        println!("❌ Unknown trait category: {}", category);
        println!("Available categories: filesystem, process, environment, io, network, memory, time");
    }
    
    Ok(())
}

fn run_interactive_mode() -> Result<()> {
    println!("🎯 Interactive Syscall Decoupling Mode");
    println!("======================================");
    
    loop {
        println!("\n🔧 Available commands:");
        println!("  1. Show syscall analysis report");
        println!("  2. Generate all decoupling traits");
        println!("  3. Generate specific trait category");
        println!("  4. Generate with SPARQL complexity data");
        println!("  5. Exit");
        
        print!("\nEnter choice (1-5): ");
        std::io::Write::flush(&mut std::io::stdout())?;
        
        let mut input = String::new();
        std::io::stdin().read_line(&mut input)?;
        
        match input.trim() {
            "1" => {
                show_syscall_report()?;
            }
            
            "2" => {
                generate_decoupling_traits("interactive_traits.rs", None, true)?;
            }
            
            "3" => {
                print!("Enter trait category (filesystem/process/environment/io/network/memory/time): ");
                std::io::Write::flush(&mut std::io::stdout())?;
                let mut category = String::new();
                std::io::stdin().read_line(&mut category)?;
                
                generate_specific_trait(category.trim(), "specific_trait.rs")?;
            }
            
            "4" => {
                // Create sample SPARQL complexity data
                let mut complexity_data = HashMap::new();
                complexity_data.insert("filesystem_ops".to_string(), 8.5);
                complexity_data.insert("process_ops".to_string(), 12.3);
                complexity_data.insert("network_ops".to_string(), 9.7);
                
                let json = serde_json::to_string_pretty(&complexity_data)?;
                
    std::fs::write("sample_complexity.json", json)?;
                
                generate_decoupling_traits("sparql_enhanced_traits.rs", Some("sample_complexity.json"), true)?;
            }
            
            "5" => {
                println!("👋 Goodbye!");
                break;
            }
            
            _ => {
                println!("❌ Invalid choice, please enter 1-5");
            }
        }
    }
    
    Ok(())
}
