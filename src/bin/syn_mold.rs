use anyhow::Result;
use clap::{Arg, Command};
use std::fs;
use proc_macro2::TokenStream;
use quote::quote;

use split_decls_rs::syn_mold::{SynMold, MoldExtraction};

fn main() -> Result<()> {
    let matches = 
    Command::new("syn-mold")
        .version("0.1.0")
        .about("Extract syn usage signatures and generate compile-time checked replacements")
        .arg(Arg::new("input")
            .short('i')
            .long("input")
            .value_name("FILE")
            .help("Input Rust file with syn usage")
            .required(true))
        .arg(Arg::new("output")
            .short('o')
            .long("output")
            .value_name("FILE")
            .help("Output file for molded code"))
        .arg(Arg::new("analysis")
            .short('a')
            .long("analysis")
            .help("Show detailed static analysis")
            .action(clap::ArgAction::SetTrue))
        .arg(Arg::new("replace")
            .short('r')
            .long("replace")
            .help("Generate replacement code using mold wrappers")
            .action(clap::ArgAction::SetTrue))
        .get_matches();

    let input_file = matches.get_one::<String>("input").unwrap();
    let output_file = matches.get_one::<String>("output");
    let show_analysis = matches.get_flag("analysis");
    let generate_replacement = matches.get_flag("replace");

    println!("🔍 syn-mold: Analyzing syn usage in {}", input_file);

    // Read and parse input file
    let input_content = fs::read_to_string(input_file)?;
    let input_tokens: proc_macro2::TokenStream = syn::parse_str(&input_content)?;

    // Create mold and extract signatures
    let mut mold = SynMold::new();
    let extraction = mold.extract_mold(input_tokens)?;

    // Show analysis if requested
    if show_analysis {
        print_analysis(&extraction);
    }

    // Generate output
    let output_code = if generate_replacement {
        extraction.generate_replacement()
    } else {
        extraction.mold_wrapper.clone()
    };

    // Write output
    if let Some(output_file) = output_file {
        fs::write(output_file, output_code.to_string())?;
        println!("✅ Molded code written to {}", output_file);
    } else {
        println!("📄 Generated mold wrapper:");
        println!("{}", output_code);
    }

    // Generate compile-time analysis report
    generate_analysis_report(&extraction, input_file)?;

    Ok(())
}

fn print_analysis(extraction: &MoldExtraction) {
    let analysis = &extraction.static_analysis;
    
    println!("\n📊 Static Analysis Results:");
    println!("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
    
    println!("🔢 Complexity Metrics:");
    println!("  Parse operations: {}", analysis.complexity_metrics.parse_operations);
    println!("  Visit operations: {}", analysis.complexity_metrics.visit_operations);
    println!("  Transform operations: {}", analysis.complexity_metrics.transform_operations);
    println!("  Generation operations: {}", analysis.complexity_metrics.generation_operations);
    println!("  Total complexity: {:.2}", analysis.complexity_metrics.total_complexity);
    
    println!("\n🔍 Extracted Signatures:");
    for (i, sig) in analysis.signatures.iter().enumerate() {
        println!("  {}. {} (complexity: {:.2})", i + 1, sig.operation, sig.complexity_score);
        println!("     Inputs: {:?}", sig.input_types);
        println!("     Outputs: {:?}", sig.output_types);
        println!("     Dependencies: {:?}", sig.dependencies);
    }
    
    println!("\n🎯 Usage Patterns:");
    for (pattern, usage) in &analysis.usage_patterns {
        println!("  {}: {:?} (frequency: {})", pattern, usage.pattern_type, usage.frequency);
    }
}

fn generate_analysis_report(extraction: &MoldExtraction, input_file: &str) -> Result<()> {
    let report_file = format!("{}_mold_report.rs", input_file.trim_end_matches(".rs"));
    let analysis = &extraction.static_analysis;
    
    let report_code = quote! {
        // Compile-time analysis report for #input_file
        // Generated by syn-mold
        
        pub mod mold_analysis_report {
            use super::*;
            
            // Compile-time constants extracted from static analysis
            pub const TOTAL_COMPLEXITY: f64 = #(analysis.complexity_metrics.total_complexity);
            pub const PARSE_OPERATIONS: u32 = #(analysis.complexity_metrics.parse_operations);
            pub const VISIT_OPERATIONS: u32 = #(analysis.complexity_metrics.visit_operations);
            pub const TRANSFORM_OPERATIONS: u32 = #(analysis.complexity_metrics.transform_operations);
            pub const GENERATION_OPERATIONS: u32 = #(analysis.complexity_metrics.generation_operations);
            
            // Signature validation at compile time
            pub trait CompileTimeValidation {
                const IS_VALID: bool;
                const COMPLEXITY_THRESHOLD: f64 = 10.0;
                
                fn validate() -> bool {
                    Self::IS_VALID && TOTAL_COMPLEXITY < Self::COMPLEXITY_THRESHOLD
                }
            }
            
            // Implementation for the analyzed code
            pub struct AnalyzedCode;
            
            impl CompileTimeValidation for AnalyzedCode {
                const IS_VALID: bool = true; // Would be computed from analysis
            }
            
            // Compile-time assertion
            const _: () = {
                assert!(AnalyzedCode::validate(), "Code complexity exceeds threshold");
            };
            
            // Usage pattern constants
            pub mod patterns {
                pub const PATTERN_COUNT: usize = #(analysis.usage_patterns.len());
                
                // Pattern-specific analysis would go here
            }
        }
    };
    
    fs::write(&report_file, report_code.to_string())?;
    println!("📋 Analysis report written to {}", report_file);
    
    Ok(())
}
