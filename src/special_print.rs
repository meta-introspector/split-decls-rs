pub fn specialprint(macro_name: &str, local_score: f64) {
    print!( ", {}: {:.4}", macro_name, local_score);
}

#[macro_export]
macro_rules! add_generated_header {
    ($path:expr, $content:expr, $invocation_file:expr, $invocation_line:expr) => {{ 
        use chrono::Utc;
        use std::io::Write; // Ensure Write trait is in scope for fs::write

        // Determine comment style based on file extension
        let path_str = $path.to_string_lossy();
        let comment_prefix = if path_str.ends_with(".toml") {
            "#"
        } else {
            "//"
        };

        // Use the new trace header system for complete traceability
        let trace_header = $crate::trace_header::generate_trace_header_with_comment_style(
            "file_generation",
            Some($invocation_file),
            "add_generated_header",
            &format!("{}:{}", $invocation_file, $invocation_line),
            comment_prefix
        );
        
        let legacy_header = format!(
            "{} Generated by add_generated_header! macro at {}:{} from {} \n{} Do not edit this file by hand. Your changes will be overwritten.\n\n",
            comment_prefix,
            $invocation_file,
            $invocation_line,
            file!(),
            comment_prefix
        );
        
        let final_content = format!("{}{}{}", trace_header, legacy_header, $content);
        
    std::fs::write($path, final_content)
    }};
}

#[macro_export]
macro_rules! add_generated_rust_header_with_result {
    ($path:expr, $content:expr, $invocation_file:expr, $invocation_line:expr) => {{ 
        use chrono::Utc;
        use std::io::Write; // Ensure Write trait is in scope for fs::write

        let source_info = format!(
            "// Generated by {} at {}:{} from {} \n// Do not edit this file by hand. Your changes will be overwritten.\n\n",
            file!(), // The file where this macro is defined (special_print.rs)
            line!(), // The line where this macro is defined (special_print.rs)
            $invocation_file, // File where this macro was invoked
            $invocation_line // Line where this macro was invoked
        );
        let final_content = source_info + $content;
        
    std::fs::write($path, final_content)
    }};
}

#[macro_export]
macro_rules! add_generated_rust_header {
    ($content:expr, $invocation_file:expr, $invocation_line:expr) => {{ 
        let source_info = format!(
            "// Generated by {} at {}:{} from {} \n// Do not edit this file by hand. Your changes will be overwritten.\n\n",
            "add_generated_rust_header! macro", // Name of the macro itself
            $invocation_file, // File where this macro was invoked
            $invocation_line, // Line where this macro was invoked
            file!() // The file where this macro is defined (special_print.rs)
        );
        source_info + $content
    }};
}
