/// Generates the file content for a single declaration and writes it to disk.
pub fn write_declaration_file(
    decl: ExtractedDecl,
    paths: &CratePaths,
    config: &SplitDeclsConfig,
    dry_run: bool,
    _common_uses: &TokenStream, // common_uses is no longer directly injected
    module_name_ident: Ident,
) -> Result<()> {
    let decl_file_path = paths.decls_output_dir.join(format!("{}.rs", module_name_ident.to_string()));
    
    let custom_prelude = if let Some(ref prelude_str) = config.custom_prelude_overlay {
        prelude_str.parse::<TokenStream>().map_err(|e| anyhow::anyhow!("Failed to parse custom prelude overlay: {}", e))?
    } else {
        quote!{}
    };

    // --- Generate Metadata Hash (ZKP Witness Placeholder) ---
    let metadata_json = serde_json::to_string(&decl.metadata)
        .context("Failed to serialize ExtractedDeclMetadata to JSON")?;
    let mut hasher = Sha256::new();
    hasher.update(metadata_json.as_bytes());
    let metadata_hash = hex::encode(hasher.finalize());
    // --- End Metadata Hash Generation ---

    // --- Generate Signature Comment ---
    let signature_comment = format!(
        "// This file was generated by split-decls-rs.\n\
         // It contains the '{}' ({}) declaration extracted from {}.\n\
         // Metadata Hash (SHA256): {}\n\
         // Please do not modify this file directly.\n\
         // This hash acts as a ZKP placeholder, summarizing the inputs and AST properties.\n\
         // Future work: Graph matching to LMFDB entries based on this metadata.",
        decl.name, decl.kind, paths.crate_name, metadata_hash
    );
    let signature = TokenStream::from_iter(vec![proc_macro2::TokenTree::Group(proc_macro2::Group::new(proc_macro2::Delimiter::None, signature_comment.parse::<TokenStream>().unwrap()))]);
    // --- End Signature Comment Generation ---

    let decl_content_ts = decl.content;
    
    let mut final_content_ts = quote! { #signature };

    // Add source location information as a comment if available
    if let Some((_, source_location)) = decl.source_map.iter().next() {
        let source_comment = format!(
            "// Source: {}:{}:{}\n",
            source_location.file,
            source_location.line,
            source_location.column
        );
        let source_comment_ts: TokenStream = source_comment.parse().unwrap();
        final_content_ts.extend(source_comment_ts);
    }
    
    final_content_ts.extend(quote! {
        use serde::{Deserialize, Serialize};
        use std::collections::HashMap; // Include HashMap for common use in generated types
        #custom_prelude // Include custom prelude if it exists
        #decl_content_ts
    });

    let initial_file_content = final_content_ts.to_string(); // Convert to string once
    
    // Add trace header for complete traceability
    let trace_header = trace_header::generate_trace_header(
        "declaration_split",
        Some(&paths.lib_rs_path.display().to_string()),
        "write_declaration_file",
        &format!("{}:{}", file!(), line!())
    );
    let traced_content = format!("{}\n{}", trace_header, initial_file_content);

    if !dry_run {
        // Write initial unformatted content with trace header
        fs::write(&decl_file_path, &traced_content)
            .context(format!("Failed to write initial content to {}", decl_file_path.display()))?;

        // Attempt to format the file
        match format_rust_file(&traced_content, &decl_file_path) {
            Ok(formatted_content) => {
                // If successful, overwrite with formatted content
                fs::write(&decl_file_path, formatted_content)
                    .context(format!("Failed to write formatted content to {}", decl_file_path.display()))?;
                info!("Split '{} {}' to {}", decl.kind, decl.name, decl_file_path.display());
            },
            Err(e) => {
                // If formatting fails, prepend a comment to the unformatted content
                let error_comment = format!(
                    "// !!! Formatting failed for this module. The following code is unformatted. !!!\n\
                     // !!! Error: {} !!!\n\n",
                    e
                );
                let content_with_error_comment = error_comment + &traced_content;
                fs::write(&decl_file_path, content_with_error_comment)
                    .context(format!("Failed to write unformatted content with error comment to {}", decl_file_path.display()))?;
                error!("\n<blip style='color:red'>Formatting error for '{} {}' (written to {})</blip>", decl.kind, decl.name, decl_file_path.display());
            }
        }
    }
    else {
        info!(
            "Dry-run: Would split '{} {}' to {}",
            decl.kind,
            decl.name,
            decl_file_path.display()
        );
    }
    Ok(())
}
