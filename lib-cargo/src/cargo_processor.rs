use std::fs;
use std::path::{Path, PathBuf};
use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use split_decls_types::SplitDeclsConfig;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PackageInfo {
    pub name: String,
    pub version: Option<String>,
    pub edition: Option<String>,
    pub authors: Option<Vec<String>>,
    pub description: Option<String>,
    pub license: Option<String>,
    pub repository: Option<String>,
    pub homepage: Option<String>,
    pub keywords: Option<Vec<String>>,
    pub categories: Option<Vec<String>>,
    pub readme: Option<String>,
    pub documentation: Option<String>,
    pub publish: Option<bool>,
    pub rust_version: Option<String>,
    pub include: Option<Vec<String>>,
    pub exclude: Option<Vec<String>>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CargoToml {
    pub package: PackageInfo,
    #[serde(default)]
    pub dependencies: HashMap<String, toml::Value>,
    #[serde(default, rename = "dev-dependencies")]
    pub dev_dependencies: HashMap<String, toml::Value>,
    #[serde(default, rename = "build-dependencies")]
    pub build_dependencies: HashMap<String, toml::Value>,
    #[serde(default)]
    pub features: Option<HashMap<String, toml::Value>>,
    #[serde(default)]
    pub workspace: Option<toml::Value>,
    #[serde(default)]
    pub profile: Option<toml::Value>,
    #[serde(flatten)]
    pub other: HashMap<String, toml::Value>,
}

/// Central cargo processor that handles all Cargo.toml operations
pub struct CargoProcessor {
    config: SplitDeclsConfig,
}

impl CargoProcessor {
    pub fn new(config: SplitDeclsConfig) -> Self {
        Self { config }
    }

    /// Process a Cargo.toml file with all dependency resolution logic
    pub fn process_cargo_toml(
        &self,
        original_path: &Path,
        output_path: &Path,
        _original_crate_root: &Path,
        dry_run: bool,
    ) -> Result<()> {
        let original_content = fs::read_to_string(original_path)
            .context(format!("Failed to read original Cargo.toml from {}", original_path.display()))?
            .replace("edition.workspace = true", "edition = \"2024\"")
            .replace("edition = \"2021\"", "edition = \"2024\"");
        
        let mut cargo_toml: CargoToml = toml::from_str(&original_content)
            .context(format!("Failed to parse original Cargo.toml from {}", original_path.display()))?;

        // Extract crate name and create wrapped version
        let original_crate_name = cargo_toml.package.name.clone();
        let wrapped_crate_name = format!("wrapped-{}", original_crate_name.replace("_", "-"));
        cargo_toml.package.name = wrapped_crate_name.clone();

        // Remove unwanted sections
        cargo_toml.other.remove("workspace");
        cargo_toml.other.remove("profile");
        
        // Convert workspace dependencies to local
        self.convert_workspace_dependencies(&mut cargo_toml)?;
        
        // Normalize all dependencies to workspace = true
        self.normalize_dependencies(&mut cargo_toml)?;
        
        // Normalize feature references
        self.normalize_feature_references(&mut cargo_toml)?;
        
        // Add build dependencies
        self.add_build_dependencies(&mut cargo_toml)?;

        if !dry_run {
            let output_content = format!(
                "# Generated by lib-cargo processor\n# Do not edit this file by hand. Your changes will be overwritten.\n\n{}",
                toml::to_string_pretty(&cargo_toml)?
            );
            
            if let Some(parent) = output_path.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(output_path, output_content)?;
        }

        Ok(())
    }

    /// Convert workspace dependency references to local dependencies
    fn convert_workspace_dependencies(&self, cargo_toml: &mut CargoToml) -> Result<()> {
        for (_, dep_value) in cargo_toml.dependencies.iter_mut() {
            if let toml::Value::Table(dep_table) = dep_value {
                if dep_table.contains_key("workspace") {
                    dep_table.remove("workspace");
                    if !dep_table.contains_key("version") {
                        dep_table.insert("version".to_string(), toml::Value::String("*".to_string()));
                    }
                }
            }
        }
        Ok(())
    }

    /// Normalize ALL dependencies to use workspace = true and handle aliases
    fn normalize_dependencies(&self, cargo_toml: &mut CargoToml) -> Result<()> {
        let dependency_tables = [
            &mut cargo_toml.dependencies,
            &mut cargo_toml.dev_dependencies, 
            &mut cargo_toml.build_dependencies,
        ];

        // Create alias map from config
        let mut alias_map = HashMap::new();
        if let Some(overrides) = &self.config.crate_path_overrides {
            for (alias_name, path) in overrides {
                if let Some(actual_name) = path.file_name().and_then(|n| n.to_str()) {
                    if alias_name != actual_name {
                        alias_map.insert(alias_name.clone(), actual_name.to_string());
                    }
                }
            }
        }

        for dep_table in dependency_tables {
            let mut deps_to_rename = Vec::new();
            
            for (dep_name, dep_value) in dep_table.iter_mut() {
                match dep_value {
                    toml::Value::Table(table) => {
                        // Remove path and version to avoid conflicts
                        table.remove("path");
                        table.remove("version");
                        // Ensure workspace = true
                        table.insert("workspace".to_string(), toml::Value::Boolean(true));
                    }
                    toml::Value::String(_) => {
                        // Convert simple string dependencies to workspace = true
                        *dep_value = {
                            let mut table = toml::value::Table::new();
                            table.insert("workspace".to_string(), toml::Value::Boolean(true));
                            toml::Value::Table(table)
                        };
                    }
                    _ => {}
                }
                
                // Check if this dependency needs to be renamed due to alias
                if let Some(actual_name) = alias_map.get(dep_name) {
                    deps_to_rename.push((dep_name.clone(), actual_name.clone(), dep_value.clone()));
                }
            }
            
            // Apply renames
            for (old_name, new_name, value) in deps_to_rename {
                dep_table.remove(&old_name);
                dep_table.insert(new_name, value);
            }
        }

        Ok(())
    }

    /// Normalize feature references to match renamed dependencies
    fn normalize_feature_references(&self, cargo_toml: &mut CargoToml) -> Result<()> {
        // Build rename table: original_name -> actual_dependency_name
        let mut rename_table = HashMap::new();
        
        // Add all dependencies to rename table
        for (dep_name, _) in &cargo_toml.dependencies {
            // Handle rust- prefix: rust-fallible-iterator -> fallible-iterator
            if let Some(original_name) = dep_name.strip_prefix("rust-") {
                rename_table.insert(original_name.to_string(), dep_name.clone());
            }
            // Handle rustc-std-workspace- prefix: rustc-std-workspace-alloc -> alloc  
            if let Some(original_name) = dep_name.strip_prefix("rustc-std-workspace-") {
                rename_table.insert(original_name.to_string(), dep_name.clone());
            }
        }
        
        // Add config overrides to rename table
        if let Some(overrides) = &self.config.crate_path_overrides {
            for (alias_name, path) in overrides {
                if let Some(actual_name) = path.file_name().and_then(|n| n.to_str()) {
                    if alias_name != actual_name {
                        rename_table.insert(alias_name.clone(), actual_name.to_string());
                    }
                }
            }
        }
        
        // Update feature references using rename table
        if let Some(features) = &mut cargo_toml.features {
            for (_, feature_list) in features.iter_mut() {
                if let toml::Value::Array(features_array) = feature_list {
                    for feature_value in features_array.iter_mut() {
                        if let toml::Value::String(feature_str) = feature_value {
                            // Handle dep:name format
                            if let Some(dep_name) = feature_str.strip_prefix("dep:") {
                                if let Some(actual_name) = rename_table.get(dep_name) {
                                    *feature_str = format!("dep:{}", actual_name);
                                }
                            }
                            // Check for dependency/feature format
                            else if let Some(slash_pos) = feature_str.find('/') {
                                let dep_name = &feature_str[..slash_pos];
                                if let Some(actual_name) = rename_table.get(dep_name) {
                                    let feature_part = &feature_str[slash_pos..];
                                    *feature_str = format!("{}{}", actual_name, feature_part);
                                }
                            } 
                            // Handle bare dependency names in features
                            else if let Some(actual_name) = rename_table.get(feature_str) {
                                *feature_str = actual_name.clone();
                            }
                        }
                    }
                }
            }
        }
        
        Ok(())
    }

    /// Add necessary build dependencies
    fn add_build_dependencies(&self, cargo_toml: &mut CargoToml) -> Result<()> {
        // Add syn with full and visit features
        let mut syn_dep = toml::value::Table::new();
        syn_dep.insert("workspace".to_string(), toml::Value::Boolean(true));
        cargo_toml.build_dependencies.insert("syn".to_string(), toml::Value::Table(syn_dep));

        // Add serde with derive feature
        let mut serde_dep = toml::value::Table::new();
        serde_dep.insert("workspace".to_string(), toml::Value::Boolean(true));
        cargo_toml.build_dependencies.insert("serde".to_string(), toml::Value::Table(serde_dep));

        // Add toml
        let mut toml_dep = toml::value::Table::new();
        toml_dep.insert("workspace".to_string(), toml::Value::Boolean(true));
        cargo_toml.build_dependencies.insert("toml".to_string(), toml::Value::Table(toml_dep));

        Ok(())
    }
}
