macro_rules! deps {
    () => {
        ManifestPath!();
        Crate!();
        Runnable!();
    };
}

macro_rules! ProjectJson {
    () => {
        deps!();
        # [doc = " Roots and crates that compose this Rust project."] # [derive (Clone , Debug , Eq , PartialEq)] pub struct ProjectJson { # [doc = " e.g. `path/to/sysroot`"] pub (crate) sysroot : Option < AbsPathBuf > , # [doc = " e.g. `path/to/sysroot/lib/rustlib/src/rust/library`"] pub (crate) sysroot_src : Option < AbsPathBuf > , # [doc = " A nested project describing the layout of the sysroot"] pub (crate) sysroot_project : Option < Box < ProjectJson > > , project_root : AbsPathBuf , # [doc = " The path to the rust-project.json file. May be None if this"] # [doc = " data was generated by the discoverConfig command."] manifest : Option < ManifestPath > , crates : Vec < Crate > , # [doc = " Configuration for CLI commands."] # [doc = ""] # [doc = " Examples include a check build or a test run."] runnables : Vec < Runnable > , }
    };
}

ProjectJson!();