use std::fs;
use std::io::Write;
use std::process::Command;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("🔧 Progressive Incremental Compiler Driver");
    println!("Testing progressively larger sets until failure");
    
    // Simulate a list of files (in real version, load from symbol map)
    let test_files = vec![
        "rustc_ast/src/lib.rs",
        "rustc_data_structures/src/lib.rs", 
        "rustc_span/src/lib.rs",
        "rustc_errors/src/lib.rs",
        "rustc_hir/src/lib.rs",
        "rustc_middle/src/lib.rs",
        "rustc_session/src/lib.rs",
        "rustc_infer/src/lib.rs",
        "rustc_trait_selection/src/lib.rs",
        "rustc_borrowck/src/lib.rs",  // This might fail
    ];
    
    println!("📁 Testing with {} files", test_files.len());
    
    // Progressive testing: start with 1 file, increase until failure
    let mut last_working_size = 0;
    
    for test_size in 1..=test_files.len() {
        println!("\n🧪 Testing with {} files...", test_size);
        
        // Generate rustc_complete.rs with first N files
        generate_rustc_complete(&test_files[..test_size])?;
        
        // Test compilation
        let success = test_compilation();
        
        if success {
            println!("✅ SUCCESS with {} files", test_size);
            last_working_size = test_size;
        } else {
            println!("❌ FAILED with {} files", test_size);
            println!("🎯 Last working size: {} files", last_working_size);
            
            // Show which file caused the failure
            if test_size > 0 {
                println!("💥 Failure caused by: {}", test_files[test_size - 1]);
            }
            break;
        }
    }
    
    // Generate final working version
    if last_working_size > 0 {
        println!("\n📝 Generating final rustc_complete.rs with {} files", last_working_size);
        generate_rustc_complete(&test_files[..last_working_size])?;
        println!("✅ Final working set saved to src/rustc_complete.rs");
    }
    
    Ok(())
}

fn generate_rustc_complete(files: &[&str]) -> Result<(), Box<dyn std::error::Error>> {
    let mut output = fs::File::create("src/rustc_complete.rs")?;
    
    writeln!(output, "// Progressive rustc_complete.rs - {} files", files.len())?;
    writeln!(output, "// Generated by progressive_driver.rs")?;
    writeln!(output)?;
    
    // Basic stubs
    writeln!(output, "pub mod ty {{")?;
    writeln!(output, "    pub struct Ty<T>(pub T);")?;
    writeln!(output, "    pub struct TyCtxt<T>(pub T);")?;
    writeln!(output, "    pub struct TypeAndMut<T> {{ pub ty: T, pub mutbl: bool }}")?;
    writeln!(output, "    pub struct Region;")?;
    writeln!(output, "}}")?;
    writeln!(output)?;
    
    writeln!(output, "pub mod def_id {{")?;
    writeln!(output, "    pub struct DefId;")?;
    writeln!(output, "    pub struct LocalDefId;")?;
    writeln!(output, "}}")?;
    writeln!(output)?;
    
    writeln!(output, "pub mod mir {{")?;
    writeln!(output, "    pub struct Body<T>(pub T);")?;
    writeln!(output, "    pub struct BasicBlock;")?;
    writeln!(output, "}}")?;
    writeln!(output)?;
    
    // Common functions and types
    writeln!(output, "pub fn bug() -> ! {{ panic!(\"bug\") }}")?;
    writeln!(output, "pub struct Span;")?;
    writeln!(output, "pub const DUMMY_SP: Span = Span;")?;
    writeln!(output)?;
    
    // Include files (commented out for now, would include actual processed files)
    writeln!(output, "// Included files:")?;
    for (i, file) in files.iter().enumerate() {
        writeln!(output, "// {}: {}", i + 1, file)?;
    }
    
    Ok(())
}

fn test_compilation() -> bool {
    println!("  🔍 Testing compilation...");
    let output = Command::new("cargo")
        .args(&["check", "--quiet"])
        .output();
    
    match output {
        Ok(result) => {
            let success = result.status.success();
            if !success {
                // Show some error details
                let stderr = String::from_utf8_lossy(&result.stderr);
                let error_lines: Vec<&str> = stderr.lines().take(3).collect();
                for line in error_lines {
                    if line.contains("error") {
                        println!("    💥 {}", line);
                    }
                }
            }
            success
        },
        Err(e) => {
            println!("    ❌ Compilation command failed: {}", e);
            false
        }
    }
}
